  const I18n = {
    paket: paket,
    bahasa: 'id',

    /** Mengganti bahasa aktif (dipanggil app.js). */
    setBahasa: function (lang) {
      this.bahasa = (lang === 'en') ? 'en' : 'id';
      return this.bahasa;
    },

    /** Mengambil teks terjemahan; mendukung placeholder {n}. */
    get: function (kunci, vars) {
      const sumber = paket[this.bahasa] || paket.id;
      let teks = sumber[kunci];
      if (teks === undefined) teks = paket.id[kunci];
      if (teks === undefined) return kunci;
      if (vars) {
        Object.keys(vars).forEach(function (v) {
          teks = teks.split('{' + v + '}').join(vars[v]);
        });
      }
      return teks;
    }
  };

